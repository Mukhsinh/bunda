export const MENU_STORAGE_KEY = 'sahabatbunda_available_menu_ids';
export const MENU_AVAILABILITY_EVENT = 'sahabatbunda_menu_availability_changed';

/**
 * Mengambil daftar ID menu yang berstatus READY / TERSEDIA
 * Default: Semua item (id: 1 s.d. 15) tersedia
 */
export function getAvailableMenuIds() {
    try {
        const stored = localStorage.getItem(MENU_STORAGE_KEY);
        if (stored) {
            const parsed = JSON.parse(stored);
            if (Array.isArray(parsed)) {
                return parsed;
            }
        }
    } catch (e) {
        console.warn('Error reading menu availability from localStorage:', e);
    }
    // Default: Semua tersedia
    const allIds = DEFAULT_MENU_ITEMS.map(item => item.id);
    try {
        localStorage.setItem(MENU_STORAGE_KEY, JSON.stringify(allIds));
    } catch {
        // ignore
    }
    return allIds;
}

/**
 * Menyimpan daftar ID menu yang tersedia dan memicu event sinkronisasi realtime
 */
export function saveAvailableMenuIds(availableIds) {
    try {
        const cleanIds = Array.isArray(availableIds) ? availableIds.map(Number) : [];
        localStorage.setItem(MENU_STORAGE_KEY, JSON.stringify(cleanIds));
        window.dispatchEvent(new CustomEvent(MENU_AVAILABILITY_EVENT, { detail: cleanIds }));
        return cleanIds;
    } catch (e) {
        console.error('Failed to save available menu ids:', e);
        return [];
    }
}

/**
 * Toggle ketersediaan menu tunggal
 */
export function toggleMenuAvailability(id) {
    const current = getAvailableMenuIds();
    const numId = Number(id);
    let updated;
    if (current.includes(numId)) {
        updated = current.filter(item => item !== numId);
    } else {
        updated = [...current, numId];
    }
    return saveAvailableMenuIds(updated);
}

/**
 * Centang semua (tersedia semua) atau hapus semua centang
 */
export function setAllMenuAvailability(isAvailable = true) {
    const allIds = isAvailable ? DEFAULT_MENU_ITEMS.map(i => i.id) : [];
    return saveAvailableMenuIds(allIds);
}

